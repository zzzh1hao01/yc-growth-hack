export function getDemoChatReply(userMessage: string): string {
  const lower = userMessage.toLowerCase();
  if (lower.includes("objection") || lower.includes("respond")) {
    return "I'd want to see the numbers in writing before I agree to anything. My agent said I'm fine.";
  }
  if (lower.includes("knock") || lower.includes("door")) {
    return "We don't really answer cold knocks. Email or a referral works better for us.";
  }
  if (lower.includes("gap") || lower.includes("coverage")) {
    return "Last time we looked was after the Tubbs fires. Construction costs have gone up a lot since then.";
  }
  return "Can you explain how you calculated the rebuild estimate? We want to understand before changing anything.";
}

